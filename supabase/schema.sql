-- OpenBenchmarkReview initial schema
-- Safe to run more than once in the Supabase SQL Editor.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  avatar_url text,
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.benchmarks (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  full_name text not null default '',
  summary text not null default '',
  category text not null check (category in ('Video generation', 'Action understanding')),
  tags text[] not null default '{}',
  year integer check (year between 1900 and 2100),
  venue text not null default '',
  status text not null default 'pending' check (status in ('pending', 'published', 'merged', 'rejected')),
  submitted_by uuid references public.profiles(id) on delete set null,
  submission_note text,
  merged_into uuid references public.benchmarks(id) on delete set null,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.benchmark_sources (
  id bigint generated by default as identity primary key,
  benchmark_id uuid not null references public.benchmarks(id) on delete cascade,
  source_type text not null check (source_type in ('github', 'huggingface', 'paper', 'project_page')),
  url text not null,
  canonical_id text,
  created_at timestamptz not null default now()
);

create unique index if not exists benchmark_sources_canonical_unique
  on public.benchmark_sources(canonical_id)
  where canonical_id is not null;
create index if not exists benchmark_sources_benchmark_idx
  on public.benchmark_sources(benchmark_id);

create table if not exists public.comments (
  id uuid primary key default gen_random_uuid(),
  benchmark_id uuid not null references public.benchmarks(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  parent_id uuid references public.comments(id) on delete cascade,
  content text not null check (char_length(content) between 2 and 8000),
  tag text not null default 'General',
  benchmark_version text,
  evidence_url text,
  status text not null default 'published' check (status in ('published', 'hidden')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists comments_benchmark_created_idx
  on public.comments(benchmark_id, created_at desc);
create index if not exists comments_parent_idx on public.comments(parent_id);

create table if not exists public.comment_votes (
  comment_id uuid not null references public.comments(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (comment_id, user_id)
);

create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references public.profiles(id) on delete cascade,
  benchmark_id uuid references public.benchmarks(id) on delete cascade,
  comment_id uuid references public.comments(id) on delete cascade,
  reason text not null check (char_length(reason) between 2 and 2000),
  status text not null default 'pending' check (status in ('pending', 'resolved', 'dismissed')),
  created_at timestamptz not null default now(),
  constraint report_has_target check (benchmark_id is not null or comment_id is not null)
);

create table if not exists public.moderation_actions (
  id uuid primary key default gen_random_uuid(),
  admin_id uuid not null references public.profiles(id) on delete restrict,
  action text not null,
  target_type text not null,
  target_id text not null,
  note text,
  created_at timestamptz not null default now()
);

