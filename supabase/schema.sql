create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text;
  v_role text := 'user';
begin
  v_username := coalesce(
    new.raw_user_meta_data ->> 'user_name',
    new.raw_user_meta_data ->> 'preferred_username',
    new.raw_user_meta_data ->> 'name',
    split_part(coalesce(new.email, 'member'), '@', 1)
  );

  if new.raw_app_meta_data ->> 'provider' = 'github'
     and lower(v_username) = 'weihangguo' then
    v_role := 'admin';
  end if;

  insert into public.profiles (id, username, avatar_url, role)
  values (new.id, v_username, new.raw_user_meta_data ->> 'avatar_url', v_role)
  on conflict (id) do update set
    username = excluded.username,
    avatar_url = excluded.avatar_url,
    role = case when excluded.role = 'admin' then 'admin' else public.profiles.role end;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert or update of raw_user_meta_data on auth.users
for each row execute function public.handle_new_user();

-- Backfill profiles for accounts that signed in before this schema was installed.
-- Dropping this first also keeps the complete script safe to re-run from SQL Editor.
drop trigger if exists profiles_protect_role on public.profiles;
insert into public.profiles (id, username, avatar_url, role)
select
  u.id,
  coalesce(
    u.raw_user_meta_data ->> 'user_name',
    u.raw_user_meta_data ->> 'preferred_username',
    u.raw_user_meta_data ->> 'name',
    split_part(coalesce(u.email, 'member'), '@', 1)
  ),
  u.raw_user_meta_data ->> 'avatar_url',
  case
    when u.raw_app_meta_data ->> 'provider' = 'github'
      and lower(coalesce(u.raw_user_meta_data ->> 'user_name', u.raw_user_meta_data ->> 'preferred_username', '')) = 'weihangguo'
    then 'admin'
    else 'user'
  end
from auth.users u
on conflict (id) do update set
  username = excluded.username,
  avatar_url = excluded.avatar_url,
  role = case when excluded.role = 'admin' then 'admin' else public.profiles.role end;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create or replace function public.protect_profile_role()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.role is distinct from old.role and not public.is_admin() then
    raise exception 'Only an administrator may change roles';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_protect_role on public.profiles;
create trigger profiles_protect_role
before update on public.profiles
for each row execute function public.protect_profile_role();

create or replace function public.canonicalize_source_url(p_url text)
returns text
language sql
immutable
as $$
  select lower(
    regexp_replace(
      regexp_replace(trim(p_url), '^https?://(www\.)?', '', 'i'),
      '/+$', ''
    )
  );
$$;

create or replace function public.submit_benchmark(
  p_name text,
  p_source_url text,
  p_category text,
  p_note text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
  v_slug text;
  v_canonical text;
  v_source_type text;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if char_length(trim(p_name)) < 2 or char_length(trim(p_name)) > 160 then
    raise exception 'Benchmark name must be between 2 and 160 characters';
  end if;
  if p_category not in ('Video generation', 'Action understanding') then
    raise exception 'Invalid benchmark category';
  end if;

  v_canonical := public.canonicalize_source_url(p_source_url);
  if v_canonical ~ '^github\.com/[^/]+/[^/]+' then
    v_source_type := 'github';
  elsif v_canonical ~ '^huggingface\.co/[^/]+/[^/]+' or v_canonical ~ '^huggingface\.co/datasets/[^/]+/[^/]+' then
    v_source_type := 'huggingface';
  else
    raise exception 'A GitHub or Hugging Face repository URL is required';
  end if;

  if exists (select 1 from public.benchmark_sources where canonical_id = v_canonical) then
    raise exception 'This repository is already indexed';
  end if;

  v_slug := trim(both '-' from regexp_replace(lower(trim(p_name)), '[^a-z0-9]+', '-', 'g'));
  if v_slug = '' then v_slug := 'benchmark'; end if;
  if exists (select 1 from public.benchmarks where slug = v_slug) then
    v_slug := v_slug || '-' || substr(replace(gen_random_uuid()::text, '-', ''), 1, 6);
  end if;

  insert into public.benchmarks (
    slug, name, category, status, submitted_by, submission_note
  ) values (
    v_slug, trim(p_name), p_category, 'pending', auth.uid(), nullif(trim(p_note), '')
  ) returning id into v_id;

  insert into public.benchmark_sources (benchmark_id, source_type, url, canonical_id)
  values (v_id, v_source_type, trim(p_source_url), v_canonical);

  return v_id;
end;
$$;

