drop policy if exists votes_owner_insert on public.comment_votes;
create policy votes_owner_insert on public.comment_votes for insert
  with check (user_id = auth.uid());
drop policy if exists votes_owner_delete on public.comment_votes;
create policy votes_owner_delete on public.comment_votes for delete
  using (user_id = auth.uid());

drop policy if exists reports_owner_insert on public.reports;
create policy reports_owner_insert on public.reports for insert
  with check (reporter_id = auth.uid());
