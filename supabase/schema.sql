drop policy if exists profiles_public_read on public.profiles;
create policy profiles_public_read on public.profiles for select using (true);
drop policy if exists profiles_owner_update on public.profiles;
create policy profiles_owner_update on public.profiles for update
  using (id = auth.uid() or public.is_admin())
  with check (id = auth.uid() or public.is_admin());

drop policy if exists benchmarks_visible_read on public.benchmarks;
create policy benchmarks_visible_read on public.benchmarks for select
  using (status = 'published' or submitted_by = auth.uid() or public.is_admin());
drop policy if exists benchmarks_admin_update on public.benchmarks;
create policy benchmarks_admin_update on public.benchmarks for update
  using (public.is_admin()) with check (public.is_admin());

drop policy if exists sources_visible_read on public.benchmark_sources;
create policy sources_visible_read on public.benchmark_sources for select
  using (exists (
    select 1 from public.benchmarks b
    where b.id = benchmark_id
      and (b.status = 'published' or b.submitted_by = auth.uid() or public.is_admin())
  ));

drop policy if exists comments_visible_read on public.comments;
create policy comments_visible_read on public.comments for select
  using (status = 'published' or user_id = auth.uid() or public.is_admin());
drop policy if exists comments_owner_insert on public.comments;
create policy comments_owner_insert on public.comments for insert
  with check (
    user_id = auth.uid()
    and exists (select 1 from public.benchmarks b where b.id = benchmark_id and b.status = 'published')
  );
drop policy if exists comments_owner_update on public.comments;
create policy comments_owner_update on public.comments for update
  using (user_id = auth.uid() or public.is_admin())
  with check (user_id = auth.uid() or public.is_admin());
drop policy if exists comments_owner_delete on public.comments;
create policy comments_owner_delete on public.comments for delete
  using (user_id = auth.uid() or public.is_admin());

drop policy if exists votes_public_read on public.comment_votes;
